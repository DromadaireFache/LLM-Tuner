SUMMARY_MARKER='<!-- Generated by llm-tune: model summary -->'


def summary_path(directory,name):
    """Preserve preset dots; GGUF paths use their basename, never directories."""
    name=str(name).replace('\\','/').rsplit('/',1)[-1]
    if name.lower().endswith('.gguf'):name=name[:-5]
    name=re.sub(r'[^a-zA-Z0-9_.-]+','-',name).strip('.-') or 'model'
    directory=pathlib.Path(directory).expanduser().resolve()
    candidate=directory/(name+'.md');suffix=0
    # Never replace a human-authored document (including the tool's README).
    while candidate.exists() and not candidate.read_text(errors='replace').startswith(SUMMARY_MARKER):
        suffix+=1
        candidate=directory/(name+'-tuning'+('' if suffix==1 else '-'+str(suffix))+'.md')
    return candidate


def atomic_text(path,text):
    path=pathlib.Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    tmp=None
    try:
        with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',dir=path.parent,prefix='.'+path.name+'-',delete=False) as f:
            tmp=pathlib.Path(f.name);f.write(text)
        tmp.replace(path)
    finally:
        if tmp and tmp.exists():tmp.unlink()


def grouped(results):
    failed={t.get('config_id') for t in results if t.get('stage') in ('screen','profile','repeat') and t.get('status') in ('oom','resource_limit','server_exit','startup_error','invalid_output','invalid_measurement','request_error','worker_error')}
    groups={}
    for t in results:
        if t.get('status')!='ok' or t.get('stage') not in ('profile','repeat'):continue
        if t.get('config_id') in failed:continue
        k=(t['config_id'],t['input_tokens'])
        groups.setdefault(k,[]).append(t)
    rows=[]
    for (cid,n),ts in groups.items():
        rows.append({'config_id':cid,'input_tokens':n,'output_tokens':ts[0].get('output_tokens',64),'repeats':len(ts),'prefill_tps':statistics.median(t['timings']['prompt_per_second'] for t in ts),'decode_tps':statistics.median(t['timings']['predicted_per_second'] for t in ts),'total_s':statistics.median(t.get('wall_s',n/t['timings']['prompt_per_second']+t.get('output_tokens',64)/t['timings']['predicted_per_second']) for t in ts),'ttft_s':statistics.median(t['ttft_s'] for t in ts),'gpu_mib':max((t.get('resources',{}).get('gpu_mib',0) for t in ts),default=0),'config':ts[0]['config']})
    return rows


def rankings(results,contexts,output_lengths):
    rows=grouped(results);byctx={};overall={}
    for n in contexts:
        rr=[r for r in rows if r['input_tokens']==n]
        if not rr:byctx[str(n)]={'coverage':'not measured'};continue
        winners={'prefill':max(rr,key=lambda r:r['prefill_tps'])['config_id'],'decode':max(rr,key=lambda r:r['decode_tps'])['config_id'],'overall':{}}
        actual=min(rr,key=lambda r:r['total_s'])
        winners['measured_overall']={'config_id':actual['config_id'],'seconds':actual['total_s'],'output_tokens':actual['output_tokens']}
        for length in output_lengths:
            best=min(rr,key=lambda r:n/r['prefill_tps']+length/r['decode_tps'])
            winners['overall'][str(length)]={'config_id':best['config_id'],'projected_seconds':n/best['prefill_tps']+length/best['decode_tps']}
        byctx[str(n)]=winners
    configs={r['config_id'] for r in rows}
    complete={cid:[r for r in rows if r['config_id']==cid] for cid in configs if all(any(r['config_id']==cid and r['input_tokens']==n for r in rows) for n in contexts)}
    if complete:
        scores={cid:statistics.mean(r['total_s'] for r in rr) for cid,rr in complete.items()}
        cid=min(scores,key=scores.get)
        overall['measured']={'config_id':cid,'measured_mean_seconds':scores[cid],'contexts':contexts,'complete_candidates':len(complete)}
    for length in output_lengths:
        if not complete:
            overall[str(length)]={'coverage':'No candidate completed every requested input length; use per-context results'};continue
        scores={cid:statistics.mean(r['input_tokens']/r['prefill_tps']+length/r['decode_tps'] for r in rr) for cid,rr in complete.items()}
        cid=min(scores,key=scores.get)
        overall[str(length)]={'config_id':cid,'projected_mean_seconds':scores[cid],'contexts':contexts,'complete_candidates':len(complete)}
    return {'per_context':byctx,'overall_across_contexts':overall},rows


def ini(config,name):
    lines=['['+name+']']
    for k,v in sorted(config.items()):
        if isinstance(v,bool):v=str(v).lower()
        lines.append(f'{k} = {v}')
    return '\n'.join(lines)+'\n'


def markdown_summary(root,doc):
    meta=doc['metadata'];rank=doc['rankings'];rows=doc['profile_rows'];results=doc['trials'];configs=doc['configurations']
    def cell(v):return html.escape(str(v)).replace('|','\\|').replace('\n','<br>')
    def table(headers,data):
        return ['| '+' | '.join(map(cell,headers))+' |','| '+' | '.join('---' for _ in headers)+' |']+['| '+' | '.join(map(cell,row))+' |' for row in data]
    def fmt(v):return f'{v:,.2f}'
    roles={}
    def winner(cid,role):
        if role not in roles.setdefault(cid,[]):roles[cid].append(role)
    byrow={(r['config_id'],r['input_tokens']):r for r in rows}
    lines=[SUMMARY_MARKER,'# '+cell(meta['model_name'])+' — tuning summary','',
           f'**Status:** {cell(doc["status"])} · **Configurations attempted:** {len(configs)} · **Budget:** {meta["budget_seconds"]:,.0f} seconds','',
           f'**Model:** `{meta["model"]["path"]}`  ',f'**Architecture:** `{meta["model"]["architecture"]}`  ',
           f'**Context capacities:** {", ".join(format(n,",") for n in meta["capacities"])} tokens  ',
           f'**Measured output:** {meta["decode_tokens"]} tokens per request  ',f'**Run folder:** `{pathlib.Path(root).resolve()}`','',
           'This is the latest run for this model, not an aggregation of earlier runs. Recommendations are suggestions; `models.ini` is not modified.','',
           '## Winners by input length','']
    if meta.get('context_mismatch'):
        mismatch=meta['context_mismatch']
        lines[lines.index('## Winners by input length'):lines.index('## Winners by input length')]=[
            '## Context configuration error','',
            f'Requested capacity: **{mismatch["requested_context"]:,} tokens**. Server request-slot capacity: **{mismatch["actual_context"]:,} tokens**. The run stopped after detecting this mismatch; no speed results are claimed.',
            f'Use a matching `--ctx-size` and input lengths no greater than {mismatch["actual_context"]-meta["decode_tokens"]:,} tokens with the current decode budget. Model metadata or per-slot settings can cap the server even when a larger KV buffer was allocated.','']
    winners=[]
    for n in meta['contexts']:
        entry=rank['per_context'][str(n)]
        if 'coverage' in entry:
            winners.append([f'{n:,}','Not measured','Not measured','Not measured']);continue
        pp=byrow[(entry['prefill'],n)];tg=byrow[(entry['decode'],n)];actual=entry['measured_overall']
        winners.append([f'{n:,}',f'{pp["config_id"]}: {fmt(pp["prefill_tps"])} t/s',f'{tg["config_id"]}: {fmt(tg["decode_tps"])} t/s',f'{actual["config_id"]}: {fmt(actual["seconds"])} s'])
        winner(pp['config_id'],'best prefill at one or more input lengths');winner(tg['config_id'],'best decode at one or more input lengths');winner(actual['config_id'],'best measured combined at one or more input lengths')
    lines+=table(['Input tokens','Best prefill','Best decode','Best measured combined'],winners)
    lines+=['',f'Measured combined time is the resident-model completion time for {meta["decode_tokens"]} output tokens. Screening results are not substituted for profile measurements; repeated measurements use medians.','',
            '## Best combined performance across contexts','']
    overall=[];primary=None
    for length,item in rank['overall_across_contexts'].items():
        if 'coverage' in item:
            overall.append([f'{length} output tokens (projected)','Not measured','—',item['coverage']]);continue
        cid=item['config_id'];measured=length=='measured'
        if measured:primary=cid
        overall.append([f'{meta["decode_tokens"]} output tokens (measured)' if measured else f'{length} output tokens (projected)',cid,fmt(item['measured_mean_seconds'] if measured else item['projected_mean_seconds']),f'{item["complete_candidates"]} fully profiled configuration(s)'])
        winner(cid,'best measured combined across contexts' if measured else f'best projected combined across contexts for {length} output tokens')
    lines+=table(['Objective','Configuration','Mean seconds','Coverage'],overall)
    lines+=['','Each requested input length has equal weight. Only configurations measured at every requested length qualify. Projected times use `input tokens / prefill t/s + output tokens / decode t/s` and exclude model loading and queueing.','',
            '### Projected combined times by workload','']
    projected=[]
    for n in meta['contexts']:
        entry=rank['per_context'][str(n)]
        if 'coverage' in entry:continue
        for length,item in entry['overall'].items():
            projected.append([f'{n:,}',length,item['config_id'],fmt(item['projected_seconds'])])
            winner(item['config_id'],'best projected combined for one or more workloads')
    if projected:lines+=table(['Input tokens','Output tokens','Best configuration','Estimated seconds'],projected)
    else:lines+=['No projections are available without successful profile measurements.']
    lines+=['',
            '## Profile measurements','']
    measurements=[]
    for r in sorted(rows,key=lambda r:(r['input_tokens'],r['config_id'])):
        measurements.append([r['config_id'],f'{int(r["config"].get("ctx-size",0)):,}',f'{r["input_tokens"]:,}',fmt(r['prefill_tps']),fmt(r['decode_tps']),fmt(r['ttft_s']),fmt(r['total_s']),f'{r["gpu_mib"]:,.0f}',r['repeats']])
    if measurements:lines+=table(['Config','Capacity','Input tokens','Prefill t/s','Decode t/s','TTFT s','Combined s','Peak GPU MiB','Repeats'],measurements)
    else:lines+=['No successful profile measurements yet. No recommended INI is claimed.']
    lines+=['','## Suggested INI sections','']
    if primary:lines+=[f'**Primary choice: {primary}**, the best measured combined result across all requested input lengths.','']
    if not roles:lines+=['No suggested INI is available because no configuration has a successful profile measurement.']
    for cid in sorted(roles,key=lambda c:(c!=primary,c)):
        if cid not in configs:continue
        lines+=['### '+cid,'','Selected for: '+ '; '.join(dict.fromkeys(roles[cid]))+'.','']
        checks=[t['check'] for t in results if t.get('config_id')==cid and t.get('stage')=='chat_check' and 'check' in t]
        if any(c.get('verification')=='passed' for c in checks):quality='Bounded chat smoke check passed; application-specific quality is not established.'
        elif any(c.get('verification')=='incomplete_token_limit' for c in checks):quality='Incomplete: the chat check reached its token limit. Review its output or increase `--check-tokens` before adopting this configuration.'
        elif checks:quality='Not verified: the chat check did not confirm a normal final answer. Review the raw result before adopting this configuration.'
        else:quality='Not checked: no completed chat smoke check is available.'
        snippet=ini(configs[cid],meta['model_name']+'-'+cid).rstrip()
        fence='`'*max(3,max((len(m.group())+1 for m in re.finditer(r'`+',snippet)),default=3))
        lines+=['**Quality check:** '+quality,'',fence+'ini',snippet,fence,'']
    lines+=['Copy only the configuration you choose into your model presets after review. Configurations with observed memory, output, or protocol failures are excluded from winner selection; budget cutoffs and skipped lengths do not count as measured results.','',
            '## Run outcomes','']
    counts={}
    for t in results:counts[t['status']]=counts.get(t['status'],0)+1
    lines+=table(['Outcome','Count'],sorted(counts.items()))
    if meta.get('router_constraints'):
        lines+=['','### Parent-server constraints','']+table(['Parameter','Fixed value'],sorted(meta['router_constraints'].items()))
    lines+=['','Full details and historical copies are in the run folder: `report.md`, `report.html`, `results.json`, and `recommendations.ini`.','']
    return '\n'.join(lines)


def write_report(root,meta,results,configs,status):
    root=pathlib.Path(root);rank,rows=rankings(results,meta['contexts'],meta['output_lengths'])
    summary=summary_path(meta.get('summary_directory',root),meta['model_name'])
    meta['markdown_summary']=str(summary)
    doc={'status':status,'metadata':meta,'rankings':rank,'profile_rows':rows,'trials':results,'configurations':configs}
    tmp=root/'results.tmp';tmp.write_text(json.dumps(doc,indent=2));tmp.replace(root/'results.json')
    text=['llama.cpp automatic tuning report',f'Model: {meta["model"]["path"]}',f'Architecture: {meta["model"]["architecture"]}',f'Budget: {meta["budget_seconds"]:.0f} seconds | Status: {status}',f'Input lengths: {meta["contexts"]} | Measured decode length: {meta["decode_tokens"]} | Capacity search: {meta["capacities"]}',f'Parent CLI constraints held fixed: {json.dumps(meta.get("router_constraints",{}),sort_keys=True)}','',
          'Winner selection uses only successful PROFILE measurements at the same input length. SCREEN results select finalists but are not substituted for long-context measurements.',
          'A configuration with an observed allocation/resource/output/protocol failure is excluded from winner selection even if another repetition succeeded. Budget cutoffs and explicitly skipped contexts are not treated as speed or stability results.',
          'Combined times are projections: input_tokens / measured_prefill_tps + target_output_tokens / measured_decode_tps. They exclude model loading, client overhead, and queuing. Cross-context scores give each requested input length equal weight; only configurations measured at every length qualify. Repeated measurements use medians.','',
          'Winners by input length']
    winners=set()
    for n,entry in rank['per_context'].items():
        if 'coverage' in entry:text.append(f'{n} input tokens: NOT MEASURED');continue
        winners.update([entry['prefill'],entry['decode']])
        text.append(f'{n} input tokens: best prefill={entry["prefill"]}; best decode={entry["decode"]}')
        actual=entry['measured_overall'];winners.add(actual['config_id'])
        text.append(f'  Best measured combined for {actual["output_tokens"]} output tokens: {actual["config_id"]}, {actual["seconds"]:.2f} s end-to-end (resident model)')
        for length,item in entry['overall'].items():
            winners.add(item['config_id']);text.append(f'  Best combined for {length} output tokens: {item["config_id"]}, projected {item["projected_seconds"]:.2f} s')
    text+=['','Best overall across requested input lengths']
    for length,item in rank['overall_across_contexts'].items():
        if length=='measured':
            winners.add(item['config_id']);text.append(f'Measured combined, {meta["decode_tokens"]} output tokens: {item["config_id"]}, mean {item["measured_mean_seconds"]:.2f} s; {item["complete_candidates"]} fully measured candidates');continue
        if 'coverage' in item:text.append(f'{length} output tokens: {item["coverage"]}')
        else:
            winners.add(item['config_id']);text.append(f'{length} output tokens: {item["config_id"]}, projected mean {item["projected_mean_seconds"]:.2f} s across {item["contexts"]}; {item["complete_candidates"]} fully measured candidates')
    text+=['','Profile measurements (medians where repeated)','config    input   prefill t/s   decode t/s   TTFT s   total s   peak GPU MiB   repeats']
    for r in sorted(rows,key=lambda r:(r['input_tokens'],r['config_id'])):
        text.append(f'{r["config_id"]:8} {r["input_tokens"]:6} {r["prefill_tps"]:13.2f} {r["decode_tps"]:12.2f} {r["ttft_s"]:8.2f} {r["total_s"]:9.2f} {r["gpu_mib"]:14.0f} {r["repeats"]:8}')
    counts={}
    for t in results:counts[t['status']]=counts.get(t['status'],0)+1
    text+=['',f'Trial outcomes: {json.dumps(counts,sort_keys=True)}',f'Unique configurations attempted: {len(configs)}',
           'Expert placement: the GGUF tensor inventory determines which layers have expert tensors. The search tries CPU-only experts, ranked repeated-layer placements, early/late placements, n-cpu-moe cuts, and measured-winner add/remove/random-subset refinements. It does not exhaust all 2^N placements. override-tensor patterns list exactly the CPU expert layers; omitted expert layers follow GPU-layer placement.',
           'Cold model load time is reported per trial separately from TTFT. Throughput runs use fixed token IDs, cache_prompt=false, greedy sampling, seed 42, and ignore_eos=true. A separate bounded chat smoke check records arithmetic/output and reasoning fields. A passed smoke check is not a broad model-quality validation; KV quantization may affect quality.',
           'Search budget includes model loads, warmups, benchmarks, and chat checks. Work is cut off at its deadline. Cleanup and restoring the serving service may take a few additional seconds. A time-budget cutoff is not a speed result.',
           'No preset was overwritten. The recommendation INIs are for review and manual installation. Temporary servers bind only to 127.0.0.1. Resource limits apply to measured VRAM/RAM headroom and swap-out; allocation errors are recorded and the next candidate is tried.',
           'For /proc RSS, mmap pages include reclaimable source pages; system available RAM also counts clean file-backed model pages as reclaimable. NVIDIA telemetry is best effort. See per-trial resources in results.json for CPU, RAM, swap, IO, and GPU measurements.',
           '', 'Winner configurations']
    snippets=[]
    for cid in sorted(winners):
        if cid not in configs:continue
        checks=[t['check'] for t in results if t.get('config_id')==cid and t.get('stage')=='chat_check' and 'check' in t]
        if not checks:text.append(cid+': quality smoke check was not completed; review output before installing.')
        elif not any(c.get('verification')=='passed' for c in checks):text.append(cid+': QUALITY CHECK NOT VERIFIED — review raw output before installing. A length-limited reasoning response may need more --check-tokens; this is distinct from a wrong answer.')
        else:text.append(cid+': bounded chat smoke check passed; full workload quality remains unverified.')
        section=meta['model_name']+'-'+cid
        snippet=ini(configs[cid],section);snippets.append(snippet)
        text += [snippet]
    if not winners:
        text += ['No complete profile measurements yet. Screening results remain available in results.json; no winner is claimed.']
    text+=['','Recovery: '+meta['recovery_command']]
    (root/'report.txt').write_text('\n'.join(text)+'\n')
    (root/'recommendations.ini').write_text('\n'.join(snippets))
    # A standalone, read-only HTML report with no external assets or network requests.
    table=''.join('<tr>'+''.join('<td>'+html.escape(str(v))+'</td>' for v in (r['config_id'],r['input_tokens'],f'{r["prefill_tps"]:.2f}',f'{r["decode_tps"]:.2f}',f'{r["ttft_s"]:.2f}',f'{r["total_s"]:.2f}',f'{r["gpu_mib"]:.0f}',r['repeats']))+'</tr>' for r in sorted(rows,key=lambda r:(r['input_tokens'],r['config_id'])))
    page='<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>LLM tuning report</title><style>body{font:16px system-ui;max-width:1100px;margin:40px auto;padding:0 24px;color:#17202a;background:#f7f8fa}h1{font-size:30px}table{border-collapse:collapse;background:white;width:100%}th,td{text-align:right;padding:10px;border-bottom:1px solid #ddd}th:first-child,td:first-child{text-align:left}pre{white-space:pre-wrap;overflow-wrap:anywhere;background:white;padding:24px;border-radius:12px;line-height:1.5}small{color:#58616b}</style><h1>LLM tuning report</h1><p>'+html.escape(meta['model_name'])+' · '+html.escape(status)+'</p><table><thead><tr><th>Configuration</th><th>Input tokens</th><th>Prefill t/s</th><th>Decode t/s</th><th>TTFT seconds</th><th>Total seconds</th><th>Peak GPU MiB</th><th>Repeats</th></tr></thead><tbody>'+table+'</tbody></table><h2>Results and recommendations</h2><pre>'+html.escape('\n'.join(text))+'</pre></html>'
    (root/'report.html').write_text(page)
    markdown=markdown_summary(root,doc)
    atomic_text(root/'report.md',markdown)
    if summary!=root.resolve()/'report.md':atomic_text(summary,markdown)
    return doc
